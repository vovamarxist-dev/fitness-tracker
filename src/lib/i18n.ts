export const DICTS: Record<Lang, Dict> = { ru, en };
export type TKey = keyof Dict;

export function makeT(lang: Lang) {
  const d = DICTS[lang];
  return (key: TKey, vars?: Record<string, string | number>) => {
    let s = d[key] ?? ru[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

/** «1 упражнение», «3 упражнения», «5 упражнений» */
export function plural(n: number, lang: Lang, forms: { ru: [string, string, string]; en: [string, string] }) {
  if (lang === 'en') return `${n} ${n === 1 ? forms.en[0] : forms.en[1]}`;
  const m10 = n % 10;
  const m100 = n % 100;
  const f = m10 === 1 && m100 !== 11 ? 0 : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 1 : 2;
  return `${n} ${forms.ru[f]}`;
}

export function fmtDuration(sec: number) {
  const s = Math.max(0, Math.round(sec));
  const m = Math.floor(s / 60);
  return `${m}:${String(s % 60).padStart(2, '0')}`;
}
